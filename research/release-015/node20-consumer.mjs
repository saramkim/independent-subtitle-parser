// Invoke with the separately acquired Node 20 binary. No global installation.
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { formatCases } from '../quality-013/format-cases.mjs';
import { loadUpstreamCases } from './oracles.mjs';
const [npmCli, output] = process.argv.slice(2);
if (!npmCli || !output) throw Error('Usage: node20-consumer.mjs <npm-cli.js> <new-report.json>');
assert.match(process.version, /^v20\./);
const manifest = JSON.parse(readFileSync('package.json'));
const tarball = resolve(`${manifest.name}-${manifest.version}.tgz`);
const hash = p => createHash('sha256').update(readFileSync(p)).digest('hex');
const before = hash(tarball);
const consumer = resolve('.package-smoke', `release-015-node20-${Date.now()}`);
mkdirSync(consumer);
writeFileSync(resolve(consumer, 'package.json'), JSON.stringify({ private: true, type: 'module' }));
const install = spawnSync(process.execPath, [resolve(npmCli), 'install', '--offline', '--ignore-scripts', '--no-audit', '--no-fund', '--cache', resolve('.package-smoke/cache'), tarball], { cwd: consumer, encoding: 'utf8', windowsHide: true, timeout: 60000 });
assert.equal(install.status, 0, install.stderr);
const entry = resolve(consumer, 'node_modules', manifest.name, 'dist/index.js');
const { parse, decode } = await import(pathToFileURL(entry).href);
for (const c of [...formatCases, ...loadUpstreamCases()]) assert.deepEqual(parse(c.source, { format: c.format }).cues.map(c => [c.start, c.end, c.text]), c.expected);
assert.equal(decode(Uint8Array.of(128, 145, 159), { encoding: 'windows-1252' }).text, '€‘Ÿ');
writeFileSync(resolve(consumer, 'consumer.cjs'), "import('independent-subtitle-parser').then(({parse})=>{if(parse('WEBVTT').format!=='vtt')process.exitCode=1;}).catch(e=>{console.error(e);process.exitCode=1;});");
const cjs = spawnSync(process.execPath, ['consumer.cjs'], { cwd: consumer, encoding: 'utf8', windowsHide: true, timeout: 10000 });
assert.equal(cjs.status, 0, cjs.stderr);
assert.equal(hash(tarball), before);
const report = { status: 'PASS', node: process.version, tarballSha256: before, checks: ['offline actual tarball installation', '33 ASS/SSA/SAMI oracles', 'windows-1252 regression', 'CommonJS dynamic import', 'unchanged tarball'] };
writeFileSync(output, JSON.stringify(report, null, 2) + '\n', { flag: 'wx' });
console.log(JSON.stringify(report, null, 2));
